CREATE TABLE IF NOT EXISTS fleet_trips (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  trip_number VARCHAR(40) NOT NULL,
  invoice_number VARCHAR(40) NULL,
  status ENUM('PENDING','APPROVED','DECLINED','IN_PROGRESS','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  horse_asset_id BIGINT UNSIGNED NOT NULL,
  trailer_asset_id BIGINT UNSIGNED NULL,
  driver_id BIGINT UNSIGNED NOT NULL,
  customer_name VARCHAR(180) NOT NULL,
  customer_address VARCHAR(500) NULL,
  customer_tax_id VARCHAR(80) NULL,
  pickup_location VARCHAR(180) NOT NULL,
  destination VARCHAR(180) NOT NULL,
  cargo_description VARCHAR(500) NOT NULL,
  cargo_quantity DECIMAL(12,3) NULL,
  cargo_unit VARCHAR(30) NULL,
  scheduled_departure DATETIME NOT NULL,
  expected_return DATETIME NULL,
  odometer_start BIGINT UNSIGNED NULL,
  odometer_end BIGINT UNSIGNED NULL,
  service_amount DECIMAL(14,2) NOT NULL DEFAULT 0,
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  tax_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
  payment_terms VARCHAR(255) NULL,
  request_reason VARCHAR(500) NULL,
  decision_reason VARCHAR(500) NULL,
  requested_by BIGINT UNSIGNED NOT NULL,
  requested_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  decided_by BIGINT UNSIGNED NULL,
  decided_at DATETIME NULL,
  completed_at DATETIME NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_fleet_trip_number (trip_number),
  UNIQUE KEY uq_fleet_trip_invoice (invoice_number),
  KEY idx_fleet_trip_status (status,scheduled_departure),
  KEY idx_fleet_trip_assets (horse_asset_id,trailer_asset_id),
  CONSTRAINT fk_fleet_trip_horse FOREIGN KEY (horse_asset_id) REFERENCES assets(id),
  CONSTRAINT fk_fleet_trip_trailer FOREIGN KEY (trailer_asset_id) REFERENCES assets(id),
  CONSTRAINT fk_fleet_trip_driver FOREIGN KEY (driver_id) REFERENCES drivers(id),
  CONSTRAINT fk_fleet_trip_requester FOREIGN KEY (requested_by) REFERENCES users(id),
  CONSTRAINT fk_fleet_trip_decider FOREIGN KEY (decided_by) REFERENCES users(id),
  CONSTRAINT chk_fleet_trip_tax CHECK (tax_percent >= 0 AND tax_percent <= 100),
  CONSTRAINT chk_fleet_trip_amount CHECK (service_amount >= 0),
  CONSTRAINT chk_fleet_trip_quantity CHECK (cargo_quantity IS NULL OR cargo_quantity >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS fleet_business_profile (
  id TINYINT UNSIGNED NOT NULL DEFAULT 1,
  business_name VARCHAR(180) NOT NULL DEFAULT '',
  business_address VARCHAR(500) NULL,
  business_phone VARCHAR(80) NULL,
  business_email VARCHAR(180) NULL,
  tax_id VARCHAR(80) NULL,
  payment_details VARCHAR(500) NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT chk_fleet_business_profile_singleton CHECK (id=1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS vehicle_inspections (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  trip_id BIGINT UNSIGNED NULL,
  asset_id BIGINT UNSIGNED NOT NULL,
  checked_by BIGINT UNSIGNED NOT NULL,
  checked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  odometer BIGINT UNSIGNED NULL,
  result ENUM('PASS','DEFECT','OUT_OF_SERVICE') NOT NULL,
  checklist_json LONGTEXT NOT NULL CHECK (JSON_VALID(checklist_json)),
  critical_defects SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  notes VARCHAR(1000) NULL,
  PRIMARY KEY (id),
  KEY idx_vehicle_inspection_asset (asset_id,checked_at),
  KEY idx_vehicle_inspection_trip (trip_id),
  CONSTRAINT fk_vehicle_inspection_trip FOREIGN KEY (trip_id) REFERENCES fleet_trips(id) ON DELETE SET NULL,
  CONSTRAINT fk_vehicle_inspection_asset FOREIGN KEY (asset_id) REFERENCES assets(id),
  CONSTRAINT fk_vehicle_inspection_user FOREIGN KEY (checked_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS driver_fitness_checks (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  trip_id BIGINT UNSIGNED NULL,
  driver_id BIGINT UNSIGNED NOT NULL,
  checked_by BIGINT UNSIGNED NOT NULL,
  checked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  licence_checked TINYINT(1) NOT NULL DEFAULT 0,
  licence_expiry DATE NULL,
  rested TINYINT(1) NOT NULL DEFAULT 0,
  fit_to_drive TINYINT(1) NOT NULL DEFAULT 0,
  result ENUM('PASS','FAIL') NOT NULL,
  notes VARCHAR(1000) NULL,
  PRIMARY KEY (id),
  KEY idx_driver_fitness_driver (driver_id,checked_at),
  KEY idx_driver_fitness_trip (trip_id),
  CONSTRAINT fk_driver_fitness_trip FOREIGN KEY (trip_id) REFERENCES fleet_trips(id) ON DELETE SET NULL,
  CONSTRAINT fk_driver_fitness_driver FOREIGN KEY (driver_id) REFERENCES drivers(id),
  CONSTRAINT fk_driver_fitness_user FOREIGN KEY (checked_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS maintenance_logs (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  asset_id BIGINT UNSIGNED NOT NULL,
  inspection_id BIGINT UNSIGNED NULL,
  reported_by BIGINT UNSIGNED NOT NULL,
  reported_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  defect_summary VARCHAR(1000) NOT NULL,
  severity ENUM('LOW','MEDIUM','HIGH','CRITICAL') NOT NULL DEFAULT 'MEDIUM',
  corrective_action VARCHAR(1000) NULL,
  resolved_by BIGINT UNSIGNED NULL,
  resolved_at DATETIME NULL,
  cost DECIMAL(14,2) NULL,
  currency CHAR(3) NULL,
  PRIMARY KEY (id),
  KEY idx_maintenance_log_asset (asset_id,reported_at),
  CONSTRAINT fk_maintenance_log_asset FOREIGN KEY (asset_id) REFERENCES assets(id),
  CONSTRAINT fk_maintenance_log_inspection FOREIGN KEY (inspection_id) REFERENCES vehicle_inspections(id) ON DELETE SET NULL,
  CONSTRAINT fk_maintenance_log_reporter FOREIGN KEY (reported_by) REFERENCES users(id),
  CONSTRAINT fk_maintenance_log_resolver FOREIGN KEY (resolved_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

